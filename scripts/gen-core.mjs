// Writes generated C++ headers in core/ardublocks from shared TypeScript data.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(root + 'src/shared/font.ts', 'utf8');
const body = src.slice(src.indexOf('[') + 1, src.lastIndexOf(']'));
const bytes = [...body.matchAll(/0x[0-9a-f]{2}/gi)].map((m) => m[0]);
if (bytes.length !== 95 * 5) throw new Error(`Font has ${bytes.length} bytes, expected ${95 * 5}`);

const lines = [];
for (let i = 0; i < bytes.length; i += 5) lines.push('  ' + bytes.slice(i, i + 5).join(', ') + ',');
const out = `// Generated by scripts/gen-core.mjs from src/shared/font.ts. Do not edit.
#pragma once

namespace ab {
static const uint8_t font5x7[] PROGMEM = {
${lines.join('\n')}
};
} // namespace ab
`;
writeFileSync(root + 'core/ardublocks/ab_font.h', out);
console.log('Wrote core/ardublocks/ab_font.h');
